import assert from 'node:assert/strict';
import { readFile, stat } from 'node:fs/promises';
import path from 'node:path';
import { projectRoot } from './photography-release.mjs';
import { validatePhotographyVideos } from './photography-video-release.mjs';
const data = JSON.parse(await readFile(path.join(projectRoot, 'src/photography/video-catalog.json'), 'utf8'));
const result = validatePhotographyVideos(data);
for (const file of result.posterPaths) assert((await stat(path.join(projectRoot, 'public', file))).size > 0);
const withPrivatePath = structuredClone(data); withPrivatePath[0].sourcePath = '/Users/private/video.mp4';
assert.throws(() => validatePhotographyVideos(withPrivatePath), /Unexpected public video fields/);
const signedSource = structuredClone(data); signedSource[0].source = 'https://example.com/temporary.mp4?token=private';
assert.throws(() => validatePhotographyVideos(signedSource), /reviewed GitHub Release/);
const credentials = structuredClone(data); credentials[0].originalUrl += '?xsec_token=private';
assert.throws(() => validatePhotographyVideos(credentials), /canonical verified-source/);
const upscaled = structuredClone(data); upscaled[0].dimensions.width = 2160;
assert.throws(() => validatePhotographyVideos(upscaled), /accepted source width/);
const duplicate = structuredClone(data); duplicate[1].id = duplicate[0].id;
assert.throws(() => validatePhotographyVideos(duplicate), /duplicate video id/);
console.log('Video release guards passed: 20 films, 11/9 categories, native dimensions, posters, immutable Release URLs, and private metadata rejection.');
